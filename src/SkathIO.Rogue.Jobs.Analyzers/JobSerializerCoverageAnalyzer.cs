using System.Collections.Concurrent;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;

namespace SkathIO.Rogue.Jobs.Analyzers;

/// <summary>
/// Reports each <c>[Job]</c> type that no <c>[JsonSerializable(typeof(T))]</c> on the project's
/// <c>JsonSerializerContext</c> covers (ROGUE019). Job payloads are serialized only through that
/// source-generated context, so an uncovered job would fail when the job registry starts. A project
/// that declares no context (its jobs may be serialized by a context in the host) is not checked.
/// </summary>
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class JobSerializerCoverageAnalyzer : DiagnosticAnalyzer
{
    private const string JobAttribute = "SkathIO.Rogue.Jobs.JobAttribute";
    private const string JsonSerializerContext = "System.Text.Json.Serialization.JsonSerializerContext";
    private const string JsonSerializableAttribute = "System.Text.Json.Serialization.JsonSerializableAttribute";

    /// <inheritdoc />
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics =>
        ImmutableArray.Create(JobsDiagnostics.JobNotSerializable);

    /// <inheritdoc />
    public override void Initialize(AnalysisContext context)
    {
        // Contexts are partly generated by the System.Text.Json generator, so generated code is read;
        // the diagnostic is reported on the job type, in user code.
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze);
        context.EnableConcurrentExecution();
        context.RegisterCompilationStartAction(static start =>
        {
            INamedTypeSymbol? jobAttribute = start.Compilation.GetTypeByMetadataName(JobAttribute);
            INamedTypeSymbol? contextType = start.Compilation.GetTypeByMetadataName(JsonSerializerContext);
            INamedTypeSymbol? serializable = start.Compilation.GetTypeByMetadataName(JsonSerializableAttribute);
            if (jobAttribute is null || contextType is null || serializable is null)
            {
                return;
            }

            var jobs = new ConcurrentDictionary<INamedTypeSymbol, bool>(SymbolEqualityComparer.Default);
            var contexts = new ConcurrentDictionary<INamedTypeSymbol, bool>(SymbolEqualityComparer.Default);
            start.RegisterSymbolAction(symbolContext =>
            {
                var type = (INamedTypeSymbol)symbolContext.Symbol;
                if (HasAttribute(type, jobAttribute))
                {
                    jobs.TryAdd(type, true);
                }
                if (DerivesFrom(type, contextType))
                {
                    contexts.TryAdd(type, true);
                }
            }, SymbolKind.NamedType);

            start.RegisterCompilationEndAction(end => ReportUncovered(end, jobs.Keys, contexts.Keys, serializable));
        });
    }

    private static void ReportUncovered(CompilationAnalysisContext context, ICollection<INamedTypeSymbol> jobs, ICollection<INamedTypeSymbol> contexts, INamedTypeSymbol serializable)
    {
        if (contexts.Count == 0 || jobs.Count == 0)
        {
            return;
        }

        var covered = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);
        INamedTypeSymbol[] ordered = contexts.OrderBy(static c => c.ToDisplayString(), System.StringComparer.Ordinal).ToArray();
        foreach (INamedTypeSymbol jsonContext in ordered)
        {
            AddCovered(jsonContext, serializable, covered);
        }

        // The fix adds to the first context, at the declaration that already carries its attributes.
        INamedTypeSymbol target = ordered[0];
        Location? targetLocation = AttributedDeclaration(target, serializable, context) ?? UserDeclaration(target, context);
        Location[] additional = targetLocation is null ? System.Array.Empty<Location>() : new[] { targetLocation };

        foreach (INamedTypeSymbol job in jobs.OrderBy(static j => j.ToDisplayString(), System.StringComparer.Ordinal))
        {
            if (!covered.Contains(job) && job.Locations.Length > 0)
            {
                context.ReportDiagnostic(Diagnostic.Create(
                    JobsDiagnostics.JobNotSerializable,
                    job.Locations[0],
                    additional,
                    ImmutableDictionary<string, string?>.Empty.Add(JobsDiagnostics.JobTypeProperty, job.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)),
                    job.ToDisplayString(),
                    target.ToDisplayString()));
            }
        }
    }

    private static void AddCovered(INamedTypeSymbol jsonContext, INamedTypeSymbol serializable, HashSet<ITypeSymbol> covered)
    {
        foreach (AttributeData attribute in jsonContext.GetAttributes())
        {
            if (IsSerializable(attribute, serializable))
            {
                covered.Add((ITypeSymbol)attribute.ConstructorArguments[0].Value!);
            }
        }
    }

    private static Location? AttributedDeclaration(INamedTypeSymbol jsonContext, INamedTypeSymbol serializable, CompilationAnalysisContext context)
    {
        foreach (AttributeData attribute in jsonContext.GetAttributes())
        {
            if (IsSerializable(attribute, serializable) && attribute.ApplicationSyntaxReference is { } reference)
            {
                // The attribute, then its attribute list, then the class declaration.
                return reference.GetSyntax(context.CancellationToken).Parent?.Parent?.GetLocation();
            }
        }
        return null;
    }

    private static bool IsSerializable(AttributeData attribute, INamedTypeSymbol serializable)
        => SymbolEqualityComparer.Default.Equals(attribute.AttributeClass, serializable)
            && attribute.ConstructorArguments.Length > 0
            && attribute.ConstructorArguments[0].Value is ITypeSymbol;

    // The context's own declaration, preferring one outside generated files, for the code fix to add to.
    private static Location? UserDeclaration(INamedTypeSymbol jsonContext, CompilationAnalysisContext context)
    {
        Location? fallback = null;
        foreach (SyntaxReference reference in jsonContext.DeclaringSyntaxReferences)
        {
            if (reference.GetSyntax(context.CancellationToken) is not ClassDeclarationSyntax declaration)
            {
                continue;
            }
            fallback ??= declaration.GetLocation();
            if (!reference.SyntaxTree.FilePath.EndsWith(".g.cs", System.StringComparison.OrdinalIgnoreCase))
            {
                return declaration.GetLocation();
            }
        }
        return fallback;
    }

    private static bool HasAttribute(INamedTypeSymbol type, INamedTypeSymbol attribute)
    {
        foreach (AttributeData data in type.GetAttributes())
        {
            if (SymbolEqualityComparer.Default.Equals(data.AttributeClass, attribute))
            {
                return true;
            }
        }
        return false;
    }

    private static bool DerivesFrom(INamedTypeSymbol type, INamedTypeSymbol baseType)
    {
        for (INamedTypeSymbol? current = type.BaseType; current is not null; current = current.BaseType)
        {
            if (SymbolEqualityComparer.Default.Equals(current, baseType))
            {
                return true;
            }
        }
        return false;
    }
}
