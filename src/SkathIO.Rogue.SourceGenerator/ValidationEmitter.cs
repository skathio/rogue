using System.Collections.Generic;

namespace SkathIO.Rogue.SourceGenerator;

/// <summary>
/// Emits <c>RogueValidation.g.cs</c>: a validator method inside each <c>[Validate]</c> partial type, the
/// implementation of the dispatcher's validation pre-handler hook for each validated request, and the
/// registration of the <c>IAsyncRules&lt;T&gt;</c> classes found in the project. The validator allocates
/// nothing while every check passes: a path string is built only for a part that failed.
/// </summary>
internal sealed class ValidationEmitter
{
    private const string Errors = "global::SkathIO.Rogue.Validation.ValidationErrors";
    private const string Culture = "global::System.Globalization.CultureInfo.InvariantCulture";

    private readonly CodeWriter _w = new CodeWriter();
    private int _locals;

    internal static string Emit(ValidationInputModel input, DiscoveredModels models)
    {
        var emitter = new ValidationEmitter();
        foreach (ValidatedTypeModel type in input.Types)
        {
            if (type.CanEmit)
            {
                emitter.EmitType(type);
            }
        }
        emitter.EmitHooks(input, models);
        emitter.EmitAsyncRulesRegistration(input.AsyncRules);
        return emitter._w.ToString();
    }

    // ── Validators inside the [Validate] types ──────────────────────────────────────

    private void EmitType(ValidatedTypeModel type)
    {
        if (type.Namespace is not null)
        {
            _w.Open("namespace " + type.Namespace);
        }
        foreach (TypeDeclarationModel declaration in type.Declarations)
        {
            _w.Open("partial " + declaration.Keyword + " " + declaration.Name);
        }

        EmitValidatorMethod(type);

        for (int i = 0; i < type.Declarations.Count; i++)
        {
            _w.Close();
        }
        if (type.Namespace is not null)
        {
            _w.Close();
        }
        _w.Line();
    }

    private void EmitValidatorMethod(ValidatedTypeModel type)
    {
        _locals = 0;
        _w.Line("/// <summary>Checks this value's rules into <paramref name=\"errors\"/>. Generated by SkathIO.Rogue; called by generated code.</summary>");
        _w.Line("[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
        _w.Open("public static void " + ValidationDiscovery.ValidatorMethodName + "(" + type.TypeFqn + " x, ref " + Errors + " errors)");
        if (type.IsReferenceType)
        {
            _w.Open("if (x is null)");
            _w.Line("return;");
            _w.Close();
        }

        // Property rules first; the Rules hook runs only when they all passed, so it can rely on them.
        if (type.HasRulesHook)
        {
            _w.Line("int start = errors.Count;");
        }
        foreach (ValidatedPropertyModel property in type.Properties)
        {
            EmitProperty(property);
        }
        if (type.HasRulesHook)
        {
            _w.Open("if (errors.Count == start)");
            _w.Line(ValidationDiscovery.RulesHookName + "(x, ref errors);");
            _w.Close();
        }
        _w.Close();
    }

    private void EmitProperty(ValidatedPropertyModel property)
    {
        string value = NextLocal("value");
        string name = Literal(property.Name);
        _w.Line("var " + value + " = x." + property.Identifier + ";");
        if (property.ImpliedNotNull)
        {
            _w.Open("if (" + value + " is null)");
            EmitNotNull(name);
            _w.Close();
            _w.Open("else");
        }
        else
        {
            OpenBlock();
        }

        foreach (RuleModel rule in property.Rules)
        {
            EmitRule(rule, value, property.Name);
        }
        if (property.Nested != NestedKind.None)
        {
            EmitNested(property, value, name);
        }
        _w.Close();
    }

    private void EmitRule(RuleModel rule, string value, string propertyName)
    {
        string arguments = rule.Arguments.Count == 0 ? string.Empty : ", " + string.Join(", ", rule.Arguments);
        string code = rule.CodeLiteral ?? rule.RuleFqn + ".DefaultCode";
        string message = rule.MessageLiteral ?? rule.RuleFqn + ".DefaultMessage(" + Literal(propertyName) + arguments + ")";
        _w.Open("if (!" + rule.RuleFqn + ".IsValid(" + value + arguments + "))");
        _w.Line("errors.Add(" + Literal(propertyName) + ", " + code + ", " + message + ");");
        _w.Close();
    }

    private void EmitNested(ValidatedPropertyModel property, string value, string name)
    {
        string target = value;
        if (property.CanBeNull)
        {
            target = NextLocal("nested");
            _w.Open("if (" + value + " is { } " + target + ")");
        }
        else
        {
            OpenBlock();
        }

        if (property.Nested == NestedKind.Object)
        {
            EmitNestedCall(property.NestedTypeFqn!, target, name);
        }
        else
        {
            EmitCollection(property, target);
        }
        _w.Close();
    }

    // Validates one nested value and prefixes the paths of the errors it added; the prefix expression
    // is evaluated only when it added any.
    private void EmitNestedCall(string typeFqn, string target, string prefixExpression)
    {
        string before = NextLocal("before");
        _w.Line("int " + before + " = errors.Count;");
        _w.Line(typeFqn + "." + ValidationDiscovery.ValidatorMethodName + "(" + target + ", ref errors);");
        _w.Open("if (errors.Count != " + before + ")");
        _w.Line("errors.PrefixSince(" + before + ", " + prefixExpression + ");");
        _w.Close();
    }

    private void EmitCollection(ValidatedPropertyModel property, string collection)
    {
        string index = NextLocal("index");
        string item = NextLocal("item");
        if (property.Shape == CollectionShape.Foreach)
        {
            _w.Line("int " + index + " = -1;");
            _w.Open("foreach (var " + item + " in " + collection + ")");
            _w.Line(index + "++;");
        }
        else
        {
            string list = NextLocal("list");
            string listType = property.Shape == CollectionShape.ReadOnlyList ? "IReadOnlyList" : "IList";
            _w.Line("global::System.Collections.Generic." + listType + "<" + property.NestedTypeFqn + "> " + list + " = " + collection + ";");
            _w.Open("for (int " + index + " = 0; " + index + " < " + list + ".Count; " + index + "++)");
            _w.Line("var " + item + " = " + list + "[" + index + "];");
        }

        string path = Literal(property.Name + "[") + " + " + index + ".ToString(" + Culture + ") + \"]\"";
        EmitCollectionItem(property, item, path);
        _w.Close();
    }

    private void EmitCollectionItem(ValidatedPropertyModel property, string item, string path)
    {
        if (!property.ItemCanBeNull)
        {
            EmitNestedCall(property.NestedTypeFqn!, item, path);
            return;
        }

        string present = NextLocal("present");
        _w.Open("if (" + item + " is { } " + present + ")");
        EmitNestedCall(property.NestedTypeFqn!, present, path);
        _w.Close();
        if (property.ItemImpliedNotNull)
        {
            _w.Open("else");
            EmitNotNull(path);
            _w.Close();
        }
    }

    private void EmitNotNull(string pathExpression)
    {
        _w.Line("errors.Add(" + pathExpression + ", \"not_null\", \"'\" + " + pathExpression + " + \"' must not be null.\");");
    }

    // A bare block that scopes one property's checks.
    private void OpenBlock()
    {
        _w.Line("{");
        _w.Indent();
    }

    private string NextLocal(string name) => name + (_locals++).ToString(System.Globalization.CultureInfo.InvariantCulture);

    private static string Literal(string text) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(text, quote: true);

    // ── Dispatcher pre-handler hooks ─────────────────────────────────────────────────

    private void EmitHooks(ValidationInputModel input, DiscoveredModels models)
    {
        // A request whose own validator could not be emitted (ROGUE014) or that comes from an assembly
        // without one (ROGUE017) gets no hook: the build already fails with that diagnostic.
        var notEmitted = new HashSet<string>();
        foreach (ValidatedTypeModel type in input.Types)
        {
            if (!type.CanEmit)
            {
                notEmitted.Add(type.TypeFqn);
            }
        }
        var skipped = new HashSet<string>(input.RequestsWithoutValidator);

        var hooks = new List<HandlerModel>();
        var seen = new HashSet<string>();
        foreach (HandlerModel handler in models.Handlers)
        {
            string requestFqn = DispatcherEmitter.ToGlobalFqn(handler.RequestFqn);
            if (FeatureModules.Marks(handler, FeatureModules.ValidationModule)
                && !notEmitted.Contains(requestFqn)
                && !skipped.Contains(handler.RequestFqn)
                && seen.Add(requestFqn))
            {
                hooks.Add(handler);
            }
        }
        if (hooks.Count == 0)
        {
            return;
        }

        _w.Open("namespace SkathIO.Rogue.Generated");
        _w.Open("internal sealed partial class RogueDispatcherImpl");
        foreach (HandlerModel handler in hooks)
        {
            EmitHook(handler);
        }
        _w.Close();
        _w.Close();
        _w.Line();
    }

    private void EmitHook(HandlerModel handler)
    {
        string requestFqn = DispatcherEmitter.ToGlobalFqn(handler.RequestFqn);
        string sendMethod = "Send_" + DispatcherEmitter.MakeSafeName(handler.RequestFqn);
        _w.Open(
            "partial void " + FeatureModules.PreHandlerHookName(FeatureModules.ValidationModule, sendMethod) +
            "(" + requestFqn + " request, global::System.Threading.CancellationToken cancellationToken)");
        _w.Line("var errors = default(" + Errors + ");");
        _w.Line(requestFqn + "." + ValidationDiscovery.ValidatorMethodName + "(request, ref errors);");
        _w.Line("errors.ThrowIfAny();");
        _w.Close();
    }

    // ── IAsyncRules<T> registration ──────────────────────────────────────────────────

    private void EmitAsyncRulesRegistration(EquatableArray<AsyncRulesModel> asyncRules)
    {
        var registered = new List<AsyncRulesModel>();
        foreach (AsyncRulesModel rules in asyncRules)
        {
            if (rules.CanRegister)
            {
                registered.Add(rules);
            }
        }
        if (registered.Count == 0)
        {
            return;
        }

        // Scoped, like the FluentValidation package's validators: async rules usually need scoped
        // services such as a DbContext. TryAddEnumerable keeps a hand registration of the same class.
        FeatureModules.OpenRegistrar(_w, "RogueValidationRegistration");
        foreach (AsyncRulesModel rules in registered)
        {
            _w.Line("global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddEnumerable(services,");
            _w.Line("    global::Microsoft.Extensions.DependencyInjection.ServiceDescriptor.Scoped<global::SkathIO.Rogue.Validation.IAsyncRules<" + rules.RequestFqn + ">, " + rules.TypeFqn + ">());");
        }
        FeatureModules.CloseRegistrar(_w);
    }
}
